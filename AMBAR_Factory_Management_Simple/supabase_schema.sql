-- Run this once in Supabase: Dashboard > SQL Editor > New query > Run
create table if not exists public.factory_items (
  id bigint generated by default as identity primary key,
  name text not null,
  stage text not null default 'Material preparation'
    check (stage in ('Material preparation','Cutting','Assembly','Finishing','Completed','Sold')),
  quantity integer not null default 0 check (quantity >= 0),
  notes text not null default '',
  created_at timestamptz not null default now()
);
alter table public.factory_items enable row level security;
